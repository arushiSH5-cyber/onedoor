import type { Metadata } from "next";
import Link from "next/link";
import { computeStats, loadRows } from "@/lib/server/stats";
import { DailyBars } from "@/components/charts";
import { HBars } from "@/components/HBars";
import { BoroughMiniMap } from "@/components/dashboard/BoroughMiniMap";
import { PATHWAY_COLOR } from "@/lib/charts/palette";
import { translate, LANG_NAMES, isLang } from "@/lib/i18n";

export const dynamic = "force-dynamic";
export const metadata: Metadata = { title: "Live screening data — OneDoor" };

const pct = (x: number) => `${Math.round(x * 100)}%`;
const secs = (s: number) => `${Math.floor(s / 60)}m ${String(s % 60).padStart(2, "0")}s`;
const BOROUGH: Record<string, string> = {
  bronx: "Bronx", brooklyn: "Brooklyn", manhattan: "Manhattan", queens: "Queens", staten_island: "Staten Island", unknown: "Not given",
};
const INCOME: Record<string, string> = {
  under60: "Under 60% AMI", "60to80": "60–80% AMI", "80to100": "80–100% AMI", over100: "Above AMI", unknown: "Unknown",
};
const MODE: Record<string, string> = { form: "Step-by-step form", text: "Free text", sms: "SMS" };

export default async function DashboardPage({ searchParams }: { searchParams: Promise<{ seed?: string }> }) {
  const { seed } = await searchParams;
  const includeSeed = seed !== "0";
  const { rows, realCount, seedCount, dbOk } = await loadRows(includeSeed);
  const s = computeStats(rows);

  const tiles = [
    { label: "Screenings", value: s.total.toLocaleString(), note: includeSeed ? `${realCount} real + ${seedCount} demo seed` : "real screenings only" },
    { label: "Likely eligible", value: pct(s.eligiblePct), note: `${s.eligible.toLocaleString()} households (EAP or Enhanced EAP)` },
    { label: "Household Link matches", value: s.linkCount.toLocaleString(), note: `${pct(s.linkPctOfEligible)} of eligible — benefit holder ≠ bill holder; today's name match misses them`, accent: true },
    { label: "Median time to finish", value: secs(s.medianSecs), note: `${pct(s.under5Pct)} finished in under 5 minutes` },
    { label: "Consent to match", value: pct(s.consentPct), note: "of eligible households opted in to address matching" },
  ];

  return (
    <div className="mx-auto max-w-6xl px-4 py-8 sm:py-10">
      <div className="flex flex-wrap items-end justify-between gap-4">
        <div>
          <p className="eyebrow">Proof it collects data</p>
          <h1 className="h1">Live screening data</h1>
          <p className="mt-1 max-w-2xl text-muted">
            Every completed screening is stored anonymized: borough, first 3 ZIP digits, language, channel, household size, income band, benefits
            present, result, Household Link flag, consent, and time to finish. No names, addresses, SSNs or exact income.
          </p>
        </div>
        <div className="flex flex-wrap gap-2">
          <div className="inline-flex rounded-xl border border-line bg-paper p-1 text-sm" role="group" aria-label="Demo seed">
            <Link href="/dashboard?seed=1" className={`rounded-lg px-3 py-1.5 font-semibold ${includeSeed ? "bg-teal-800 text-white" : "text-teal-800"}`}>
              Demo seed: on
            </Link>
            <Link href="/dashboard?seed=0" className={`rounded-lg px-3 py-1.5 font-semibold ${!includeSeed ? "bg-teal-800 text-white" : "text-teal-800"}`}>
              Real only
            </Link>
          </div>
          <a href={`/api/export?seed=${includeSeed ? 1 : 0}`} className="btn-ghost py-2 text-sm" download>
            ⬇ Export CSV
          </a>
        </div>
      </div>

      {!dbOk && (
        <p className="mt-6 rounded-xl bg-brick-100 p-4 text-sm text-brick-600" role="alert">
          The database is not reachable, so no data can be shown. Set DATABASE_URL (see README) and run <code>npm run db:push</code>.
        </p>
      )}
      {includeSeed && seedCount > 0 && (
        <p className="mt-6 rounded-xl border border-amber-500/40 bg-amber-100 p-3 text-sm text-teal-900">
          <strong>Includes {seedCount} synthetic “demo seed” records</strong> generated by <code>scripts/seed.ts</code> (pathways computed by the
          real rules engine) so the charts are readable before launch. Switch to <Link href="/dashboard?seed=0" className="underline">Real only</Link> to
          see the {realCount} screenings people have actually completed.
        </p>
      )}

      <div className="mt-6 grid gap-3 sm:grid-cols-2 lg:grid-cols-5">
        {tiles.map((t) => (
          <div key={t.label} className={`card ${t.accent ? "border-2 border-amber-500" : ""}`}>
            <p className="text-sm font-medium text-muted">{t.label}</p>
            <p className="mt-1 font-display text-3xl font-semibold text-teal-900 tabular-nums">{t.value}</p>
            <p className="mt-1 text-xs text-muted">{t.note}</p>
          </div>
        ))}
      </div>

      <div className="mt-4 grid gap-4 lg:grid-cols-3">
        <section className="card lg:col-span-2">
          <h2 className="font-semibold text-teal-900">Screenings per day (last 21 days)</h2>
          <DailyBars data={s.perDay} />
        </section>
        <section className="card">
          <h2 className="mb-4 font-semibold text-teal-900">Result</h2>
          <HBars data={s.byPathway} label={(k) => translate("en", `pathwayShort.${k}`)} color={(k) => PATHWAY_COLOR[k] ?? "#9aa5ab"} />
        </section>
        <section className="card">
          <h2 className="mb-4 font-semibold text-teal-900">Language</h2>
          <HBars data={s.byLanguage} label={(k) => (isLang(k) ? LANG_NAMES[k] : k)} />
        </section>
        <section className="card">
          <h2 className="mb-4 font-semibold text-teal-900">Channel</h2>
          <HBars data={s.byMode} label={(k) => MODE[k] ?? k} />
          <h2 className="mt-6 mb-4 font-semibold text-teal-900">Income band</h2>
          <HBars data={s.byIncome} label={(k) => INCOME[k] ?? k} />
        </section>
        <section className="card">
          <h2 className="mb-4 font-semibold text-teal-900">Benefits present in household</h2>
          <HBars data={s.byBenefit} total={s.total} label={(k) => translate("en", `benefitShort.${k}`).replace(/^a /, "")} />
          <p className="mt-3 text-xs text-muted">% of all screenings with at least one member receiving each benefit.</p>
        </section>
        <section className="card lg:col-span-2">
          <h2 className="mb-2 font-semibold text-teal-900">Screenings by borough</h2>
          <BoroughMiniMap counts={Object.fromEntries(s.byBorough.map((d) => [d.key, d.value]))} />
        </section>
        <section className="card">
          <h2 className="mb-4 font-semibold text-teal-900">By borough</h2>
          <HBars data={s.byBorough} label={(k) => BOROUGH[k] ?? k} />
        </section>
      </div>

      <section className="card mt-4 overflow-x-auto">
        <h2 className="mb-3 font-semibold text-teal-900">Most recent screenings</h2>
        <table className="w-full min-w-[720px] text-left text-sm">
          <thead className="text-muted">
            <tr className="border-b border-line">
              {["Time", "Borough", "ZIP3", "Lang", "Channel", "Size", "Income", "Benefits", "Result", "Link", "Consent", "Secs", ""].map((h) => (
                <th key={h} className="py-2 pr-3 font-medium">{h}</th>
              ))}
            </tr>
          </thead>
          <tbody>
            {s.recent.map((r, i) => (
              <tr key={i} className="border-b border-line/60">
                <td className="py-2 pr-3 whitespace-nowrap tabular-nums">{r.createdAt.toISOString().slice(0, 16).replace("T", " ")}</td>
                <td className="pr-3">{BOROUGH[r.borough ?? "unknown"]}</td>
                <td className="pr-3 tabular-nums">{r.zip3 ?? "—"}</td>
                <td className="pr-3">{r.language}</td>
                <td className="pr-3">{r.inputMode}</td>
                <td className="pr-3 tabular-nums">{r.householdSize}</td>
                <td className="pr-3">{r.incomeBracket}</td>
                <td className="pr-3">{r.benefits || "—"}</td>
                <td className="pr-3">{r.pathway}</td>
                <td className="pr-3">{r.householdLink ? "✓" : ""}</td>
                <td className="pr-3">{r.consentGiven ? "✓" : ""}</td>
                <td className="pr-3 tabular-nums">{r.completionSecs}</td>
                <td>{r.isDemoSeed && <span className="badge bg-amber-100 px-2 py-0.5 text-xs">demo</span>}</td>
              </tr>
            ))}
          </tbody>
        </table>
        {s.recent.length === 0 && <p className="py-4 text-sm text-muted">No screenings yet. <Link href="/check" className="underline">Run one</Link>.</p>}
      </section>
    </div>
  );
}
